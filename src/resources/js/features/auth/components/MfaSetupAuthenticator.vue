<script setup lang="ts">
import Overlay from "@/core/components/Overlay.vue";
import TwoFactorForm from "../forms/TwoFactorForm.vue";
import { confirm } from "@/wayfinder/routes/two-factor";
import { dataGet, dataPost, isLoading } from "@/core/services/axiosWrapper";
import { onMounted, ref } from "vue";
import { enable, qrCode } from "@/wayfinder/routes/two-factor";

interface twoFaResponseData {
    svg: string;
    url: string;
}

const props = defineProps<{
    allowRemember: boolean;
}>();

const qrUrl = ref();
const qrImage = ref();

/**
 * Enable 2FA via Authenticator App
 */
const enableQrCode = () => {
    dataPost(enable.url(), {}).then(() => {
        getQrCode();
    });
};

/**
 * Get QR Code for user to scan and assign to Authenticator App
 */
const getQrCode = async () => {
    const mfaData = await dataGet<twoFaResponseData>(qrCode.url());

    if (mfaData) {
        qrImage.value = mfaData.svg;
        qrUrl.value = mfaData.url;
    }
};

onMounted(() => enableQrCode());
</script>

<template>
    <Overlay :loading="isLoading">
        <h3 class="text-center">
            Scan the QR Code below with your Authenticator App, or click on the
            QR Code from your mobile device.
        </h3>
        <div class="flex justify-center my-3">
            <a :href="qrUrl" v-html="qrImage" class="min-h-32" />
        </div>
        <h4 class="text-center">
            Enter the code generated by the Authenticator App to confirm setup.
        </h4>
        <TwoFactorForm
            :allow-remember="allowRemember"
            :submit-route="confirm.url()"
        />
    </Overlay>
</template>
