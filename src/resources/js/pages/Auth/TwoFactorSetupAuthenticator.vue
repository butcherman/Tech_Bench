<script setup lang="ts">
import AppLayout from "@/layouts/AppLayout.vue";
import Overlay from "@/core/components/Overlay.vue";
import TwoFactorForm from "@/features/auth/forms/TwoFactorForm.vue";
import { ref, onMounted } from "vue";
import { dataGet, dataPost, isLoading } from "@/core/utilities/axiosWrapper";
import { enable, qrCode, confirm } from "@/wayfinder/routes/two-factor";

interface mfaResponse {
    svg: string;
    url: string;
}

defineOptions({ layout: AppLayout });

const qrCodeImage = ref<string>();
const qrUrl = ref<string>();

/**
 * Get the QR Code Image from server
 */
const getQrCode = async () => {
    dataPost(enable.url(), []).then(() => {
        dataGet<mfaResponse>(qrCode.url()).then((res) => {
            if (res) {
                qrCodeImage.value = res.svg;
                qrUrl.value = res.url;
            }
        });
    });
};

onMounted(() => getQrCode());
</script>

<template>
    <div>
        <div class="border-b border-slate-300 mb-3 pb-4">
            <h1>Authenticator App Setup</h1>
        </div>
        <div class="flex justify-center">
            <Overlay :loading="isLoading" class="w-full lg:w-1/2">
                <h3 class="text-center">
                    Scan the QR Code below with your Authenticator App, or click
                    on the QR Code from your mobile device.
                </h3>
                <div class="flex justify-center my-3">
                    <a :href="qrUrl" v-html="qrCodeImage" class="min-h-32" />
                </div>
                <h4 class="text-center">
                    Enter the code generated by the Authenticator App to confirm
                    setup.
                </h4>
                <div>
                    <TwoFactorForm
                        :allow-remember="false"
                        :submit-route="confirm.url()"
                    />
                </div>
            </Overlay>
        </div>
    </div>
</template>
